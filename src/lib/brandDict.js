const COMPILED = BRAND_PATTERNS.map(([name, src]) => [name, new RegExp(src, 'i')]);

export const KNOWN_BRANDS = new Set(BRAND_PATTERNS.map(([name]) => name));

// 商品名からブランドを判定する。当たらなければ ''。
export function detectBrand(itemName) {
  // 「エルゴ互換」「レゴ互換」のような互換品は、そのブランドの商品ではない
  if (/互換/.test(String(itemName || ''))) return '';
  const n = String(itemName || '').replace(/[Ａ-Ｚａ-ｚ０-９＆]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0));
  for (const [name, re] of COMPILED) {
    if (re.test(n)) return name;
  }
  return '';
}
